"""Auto-build the component catalogue from component HTML files.

Scans all subdirectories in components/, reads the comment block at the top
of each .html file, and writes catalogue.md with the full index.

Run this script whenever the skill is loaded to ensure the catalogue is current.

Usage:
    python components/build_catalogue.py
"""

import re
from pathlib import Path


def extract_comment_block(html_path: Path) -> dict[str, str]:
    """Extract the structured comment block from the top of an HTML component file.

    Expects a comment block like:
    <!--
    Component: Chevron Divider
    Source: v1_chevron_flow
    Feedback: "Chevrons are great..."
    When to use: Between sections to create downward flow
    -->
    """
    text = html_path.read_text(encoding="utf-8")
    match = re.search(r"<!--\s*(.*?)\s*-->", text, re.DOTALL)
    if not match:
        return {"name": html_path.stem, "description": "No description found."}

    block = match.group(1).strip()
    fields: dict[str, str] = {}
    current_key = None
    current_lines: list[str] = []

    for line in block.splitlines():
        kv_match = re.match(r"^([\w\s]+?):\s*(.*)$", line.strip())
        if kv_match:
            if current_key:
                fields[current_key] = " ".join(current_lines).strip()
            current_key = kv_match.group(1).strip().lower()
            current_lines = [kv_match.group(2).strip()]
        elif current_key:
            current_lines.append(line.strip())

    if current_key:
        fields[current_key] = " ".join(current_lines).strip()

    return fields


def build_catalogue() -> str:
    """Scan all component directories and build the catalogue markdown."""
    components_dir = Path(__file__).parent
    categories = sorted(
        [d for d in components_dir.iterdir() if d.is_dir()],
        key=lambda d: d.name,
    )

    lines = [
        "# Component Library Catalogue",
        "",
        "Auto-generated by `build_catalogue.py`. Do not edit manually.",
        "",
        "Browse these components for visual inspiration when creating one-pagers ",
        "and decks. Pick 2-3, remix creatively, and invent new patterns freely.",
        "",
    ]

    total = 0
    for category_dir in categories:
        html_files = sorted(category_dir.glob("*.html"))
        if not html_files:
            continue

        category_name = category_dir.name.replace("_", " ").title()
        lines.append(f"## {category_name}")
        lines.append("")

        for html_file in html_files:
            fields = extract_comment_block(html_file)
            rel_path = html_file.relative_to(components_dir)
            name = fields.get(
                "component",
                fields.get("name", html_file.stem.replace("_", " ").title()),
            )
            source = fields.get("source", "")
            feedback = fields.get("feedback", fields.get("user feedback", ""))
            when = fields.get("when to use", "")

            lines.append(f"### [{name}]({rel_path})")
            if source:
                lines.append(f"- **Source**: {source}")
            if feedback:
                lines.append(f"- **Feedback**: {feedback}")
            if when:
                lines.append(f"- **When to use**: {when}")
            lines.append("")
            total += 1

    lines.insert(7, f"**{total} components** across {len(categories)} categories.\n")

    return "\n".join(lines)


def main() -> None:
    catalogue_path = Path(__file__).parent / "catalogue.md"
    content = build_catalogue()
    catalogue_path.write_text(content, encoding="utf-8")
    print(f"Catalogue written to {catalogue_path} ({content.count('###')} components)")


if __name__ == "__main__":
    main()
